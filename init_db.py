"""Idempotent database bootstrap for ZoneMatrix.

Applies ``schema.sql`` (DDL + seed rows) to the database named by
``DATABASE_URL``. Render runs this as the service's ``preDeployCommand``,
so it executes before every deploy and must be safe to re-run:

  * every DDL statement uses ``IF NOT EXISTS``;
  * seed rows use ``ON CONFLICT DO NOTHING``;
  * identity sequences are pushed past any seeded ids afterwards.

Usage:
    python init_db.py            # uses DATABASE_URL / PG* from the environment
    python init_db.py --check    # only verify connectivity, apply nothing
"""

from __future__ import annotations

import argparse
import os
import sys

import psycopg2
from psycopg2 import sql

# Reuses the app's DSN resolution (reads .env locally, DATABASE_URL on Render).
from api import db

SCHEMA_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "schema.sql")


def split_statements(script: str) -> list[str]:
    """Split a SQL script on semicolons, ignoring those inside literals/comments."""
    statements: list[str] = []
    buffer: list[str] = []
    in_single = False
    in_double = False
    in_line_comment = False
    i = 0
    while i < len(script):
        ch = script[i]
        nxt = script[i + 1] if i + 1 < len(script) else ""

        if in_line_comment:
            if ch == "\n":
                in_line_comment = False
                buffer.append(ch)
            i += 1
            continue

        if in_single:
            buffer.append(ch)
            if ch == "'":
                if nxt == "'":  # escaped quote
                    buffer.append(nxt)
                    i += 2
                    continue
                in_single = False
            i += 1
            continue

        if in_double:
            buffer.append(ch)
            if ch == '"':
                in_double = False
            i += 1
            continue

        if ch == "-" and nxt == "-":
            in_line_comment = True
            i += 2
            continue
        if ch == "'":
            in_single = True
            buffer.append(ch)
        elif ch == '"':
            in_double = True
            buffer.append(ch)
        elif ch == ";":
            statement = "".join(buffer).strip()
            if statement:
                statements.append(statement)
            buffer = []
        else:
            buffer.append(ch)
        i += 1

    tail = "".join(buffer).strip()
    if tail:
        statements.append(tail)
    return statements


def advance_identity_sequences(conn: psycopg2.extensions.connection) -> None:
    """Make ``GENERATED BY DEFAULT AS IDENTITY`` columns continue after seeds.

    Inserting explicit ids does not move an identity sequence, so the next
    app-side INSERT would collide with a seeded row. Setting each sequence to
    ``max(id) + 1`` (never backwards into an existing row) fixes that.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT table_name, column_name
            FROM information_schema.columns
            WHERE table_schema = 'public' AND is_identity = 'YES'
            ORDER BY table_name, column_name
            """
        )
        identity_columns = cur.fetchall()

    for table_name, column_name in identity_columns:
        # pg_get_serial_sequence() takes text arguments, so bind them as
        # parameters; the identifiers are interpolated via Identifier.
        statement = sql.SQL(
            "SELECT setval(pg_get_serial_sequence(%s, %s), "
            "COALESCE(MAX({column}), 0) + 1, false) FROM {table}"
        ).format(
            table=sql.Identifier(table_name),
            column=sql.Identifier(column_name),
        )
        with conn.cursor() as cur:
            cur.execute(statement, (table_name, column_name))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify connectivity only; do not apply schema.sql",
    )
    args = parser.parse_args()

    dsn = db._dsn()
    # Never echo credentials.
    safe_dsn = dsn.split("@")[-1] if "@" in dsn else dsn
    print(f"[init_db] connecting to {safe_dsn}")

    try:
        conn = psycopg2.connect(dsn, connect_timeout=15)
    except Exception as exc:  # noqa: BLE001 - report and fail the deploy
        print(f"[init_db] connection failed: {exc}", file=sys.stderr)
        return 1

    try:
        if args.check:
            with conn.cursor() as cur:
                cur.execute("SELECT version()")
                print(f"[init_db] ok: {cur.fetchone()[0][:60]}...")
            return 0

        with open(SCHEMA_PATH, encoding="utf-8") as handle:
            statements = split_statements(handle.read())

        conn.autocommit = True
        with conn.cursor() as cur:
            for index, statement in enumerate(statements, start=1):
                cur.execute(statement)
            advance_identity_sequences(conn)

        print(f"[init_db] applied {len(statements)} statements from schema.sql")
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT
                  (SELECT count(*) FROM users)      AS users,
                  (SELECT count(*) FROM zones)      AS zones,
                  (SELECT count(*) FROM zone_configs) AS zone_configs
                """
            )
            users, zones, zone_configs = cur.fetchone()
        print(
            f"[init_db] ready: {users} users, {zones} zones, "
            f"{zone_configs} zone_configs"
        )
        return 0
    except psycopg2.Error as exc:
        print(f"[init_db] failed: {exc}", file=sys.stderr)
        if getattr(exc, "pgcode", None):
            print(f"[init_db] sqlstate: {exc.pgcode}", file=sys.stderr)
        return 1
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
