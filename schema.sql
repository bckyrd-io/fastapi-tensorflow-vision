-- ZoneMatrix PostgreSQL schema (idempotent).
--
-- Mirrors the local `db_zone` database: 11 tables, identity primary keys,
-- foreign keys, CHECK constraints, indexes and the seed rows the app expects.
-- Applied by `init_db.py` on every Render deploy, so it must be safe to run
-- repeatedly against an already-initialised database.
--
-- Tables are created in dependency order so every FOREIGN KEY target exists.

-- ------------------------------------------------------------------ zones --
CREATE TABLE IF NOT EXISTS zones (
    id              character varying(10) NOT NULL,
    name            character varying(100) NOT NULL,
    location        character varying(200),
    size_sqm        numeric,
    depth_m         numeric,
    species         character varying(50),
    status          character varying(10) DEFAULT 'active' NOT NULL,
    created_at      timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    zone_type       character varying(20) DEFAULT 'greenhouse' NOT NULL,
    subject_name    character varying(100) DEFAULT 'Tomato (Roma)',
    CONSTRAINT zones_pkey PRIMARY KEY (id),
    CONSTRAINT zones_status_check CHECK (status IN ('active', 'inactive')),
    CONSTRAINT zones_zone_type_check CHECK (zone_type IN ('greenhouse', 'pond', 'pen_kraal', 'custom'))
);

-- ------------------------------------------------------------------ users --
CREATE TABLE IF NOT EXISTS users (
    id              integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username        character varying(50) NOT NULL,
    email           character varying(100) NOT NULL,
    password_hash   character varying(255) NOT NULL,
    full_name       character varying(100),
    role            character varying(10) DEFAULT 'operator' NOT NULL,
    is_active       boolean DEFAULT true NOT NULL,
    last_login      timestamp with time zone,
    created_at      timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('admin', 'operator', 'viewer'))
);

-- ------------------------------------------------------------ zone_configs --
CREATE TABLE IF NOT EXISTS zone_configs (
    zone_id             character varying(10) NOT NULL,
    temp_min            numeric DEFAULT 24.00,
    temp_optimal        numeric DEFAULT 26.00,
    temp_max            numeric DEFAULT 28.00,
    ph_min              numeric DEFAULT 6.50,
    ph_optimal          numeric DEFAULT 7.00,
    ph_max              numeric DEFAULT 8.00,
    humidity_min        integer DEFAULT 60,
    humidity_optimal    integer DEFAULT 75,
    humidity_max        integer DEFAULT 85,
    water_level_min     numeric DEFAULT 0.80,
    water_level_optimal numeric DEFAULT 1.50,
    water_level_max     numeric DEFAULT 1.80,
    device_id           character varying(50),
    device_name         character varying(100),
    device_mac          character varying(17),
    CONSTRAINT zone_configs_pkey PRIMARY KEY (zone_id),
    CONSTRAINT zone_configs_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------- sensors --
CREATE TABLE IF NOT EXISTS sensors (
    id          character varying(20) NOT NULL,
    zone_id     character varying(10),
    type        character varying(20),
    status      character varying(10) DEFAULT 'active' NOT NULL,
    created_at  timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT sensors_pkey PRIMARY KEY (id),
    CONSTRAINT sensors_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE,
    CONSTRAINT sensors_status_check CHECK (status IN ('active', 'inactive')),
    CONSTRAINT sensors_type_check CHECK (type IN ('temperature', 'ph', 'humidity', 'water_level'))
);

-- --------------------------------------------------------- sensor_readings --
CREATE TABLE IF NOT EXISTS sensor_readings (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    zone_id       character varying(10),
    temperature   numeric,
    ph            numeric,
    humidity      integer,
    water_level   numeric,
    device_id     character varying(50),
    reading_time  timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT sensor_readings_pkey PRIMARY KEY (id),
    CONSTRAINT sensor_readings_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE
);

-- --------------------------------------------------------- captured_frames --
CREATE TABLE IF NOT EXISTS captured_frames (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    zone_id       character varying(10) NOT NULL,
    image_url     character varying(255) NOT NULL,
    source        character varying(20) DEFAULT 'expo_camera_auto' NOT NULL,
    captured_at   timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT captured_frames_pkey PRIMARY KEY (id),
    CONSTRAINT captured_frames_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE,
    CONSTRAINT captured_frames_source_check CHECK (source IN ('expo_camera_auto', 'expo_camera_manual', 'field_upload'))
);

-- -------------------------------------------------------- trigger_schedules --
CREATE TABLE IF NOT EXISTS trigger_schedules (
    id                integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    zone_id           character varying(10) NOT NULL,
    time              time without time zone,
    interval_minutes  integer,
    duration_seconds  integer DEFAULT 0,
    days              character varying(50) DEFAULT 'Daily',
    actuator_name     character varying(50) DEFAULT 'pellets',
    active            boolean DEFAULT false NOT NULL,
    last_executed     timestamp with time zone,
    created_at        timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at        timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT trigger_schedules_pkey PRIMARY KEY (id),
    CONSTRAINT trigger_schedules_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE
);

-- ------------------------------------------------------------ trigger_logs --
CREATE TABLE IF NOT EXISTS trigger_logs (
    id                  integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    zone_id             character varying(10) NOT NULL,
    schedule_id         integer,
    duration_seconds    integer NOT NULL,
    actuator_name       character varying(50),
    triggered_by        character varying(10) DEFAULT 'schedule' NOT NULL,
    triggered_by_user   character varying(50),
    device_id           character varying(50),
    status              character varying(20) DEFAULT 'pending' NOT NULL,
    triggered_at        timestamp with time zone,
    created_at          timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT trigger_logs_pkey PRIMARY KEY (id),
    CONSTRAINT trigger_logs_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE,
    CONSTRAINT trigger_logs_schedule_id_fkey FOREIGN KEY (schedule_id) REFERENCES trigger_schedules (id) ON DELETE SET NULL,
    CONSTRAINT trigger_logs_status_check CHECK (status IN ('pending', 'in_progress', 'completed', 'failed')),
    CONSTRAINT trigger_logs_triggered_by_check CHECK (triggered_by IN ('schedule', 'manual'))
);

-- ------------------------------------------------------- stage_predictions --
CREATE TABLE IF NOT EXISTS stage_predictions (
    id                integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    frame_id          integer NOT NULL,
    zone_id           character varying(10) NOT NULL,
    model_name        character varying(50) DEFAULT 'growth_stage_model.h5' NOT NULL,
    predicted_stage   character varying(50) NOT NULL,
    confidence        numeric NOT NULL,
    raw_probabilities jsonb,
    nailed_it         boolean,
    validated_at      timestamp with time zone,
    created_at        timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT stage_predictions_pkey PRIMARY KEY (id),
    CONSTRAINT stage_predictions_frame_id_fkey FOREIGN KEY (frame_id) REFERENCES captured_frames (id) ON DELETE CASCADE,
    CONSTRAINT stage_predictions_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------- alerts --
CREATE TABLE IF NOT EXISTS alerts (
    id                integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    zone_id           character varying(10),
    type              character varying(10) DEFAULT 'info' NOT NULL,
    message           text NOT NULL,
    source            character varying(10) DEFAULT 'system' NOT NULL,
    status            character varying(10) DEFAULT 'active' NOT NULL,
    value             numeric,
    parameter         character varying(20),
    acknowledged_by   character varying(50),
    acknowledged_at   timestamp with time zone,
    created_at        timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT alerts_pkey PRIMARY KEY (id),
    CONSTRAINT alerts_zone_id_fkey FOREIGN KEY (zone_id) REFERENCES zones (id) ON DELETE CASCADE,
    CONSTRAINT alerts_type_check CHECK (type IN ('critical', 'warning', 'info')),
    CONSTRAINT alerts_source_check CHECK (source IN ('trigger', 'sensor', 'config', 'user', 'system')),
    CONSTRAINT alerts_status_check CHECK (status IN ('active', 'inactive')),
    CONSTRAINT alerts_parameter_check CHECK (parameter IS NULL OR parameter IN ('temperature', 'ph', 'humidity', 'water_level'))
);

-- -------------------------------------------------------- trigger_presets --
CREATE TABLE IF NOT EXISTS trigger_presets (
    preset_id   character varying(20) NOT NULL,
    active      boolean DEFAULT true NOT NULL,
    updated_at  timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT trigger_presets_pkey PRIMARY KEY (preset_id)
);

-- ---------------------------------------------------------------- indexes --
CREATE INDEX IF NOT EXISTS idx_alerts_status_type ON alerts (status, type);
CREATE INDEX IF NOT EXISTS idx_alerts_source ON alerts (source);
CREATE INDEX IF NOT EXISTS idx_alerts_created ON alerts (created_at);
CREATE INDEX IF NOT EXISTS idx_alerts_zone ON alerts (zone_id);
CREATE INDEX IF NOT EXISTS idx_sensor_readings_zone_time ON sensor_readings (zone_id, reading_time);
CREATE INDEX IF NOT EXISTS idx_sensors_zone ON sensors (zone_id);
CREATE INDEX IF NOT EXISTS idx_predictions_zone ON stage_predictions (zone_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_predictions_nailed_it ON stage_predictions (nailed_it);
CREATE INDEX IF NOT EXISTS idx_trigger_logs_zone_created ON trigger_logs (zone_id, created_at);
CREATE INDEX IF NOT EXISTS idx_trigger_logs_schedule ON trigger_logs (schedule_id);
CREATE INDEX IF NOT EXISTS idx_trigger_schedules_zone_active ON trigger_schedules (zone_id, active);

