$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$venvPython = Join-Path $repoRoot '.venv\Scripts\python.exe'
$frontendDir = Join-Path $repoRoot 'green-matrix'
$frontendEnv = Join-Path $frontendDir '.env'

if (-not (Test-Path $venvPython)) {
    throw "Missing Python venv at $venvPython. Run: py -m venv .venv ; .\.venv\Scripts\python.exe -m pip install -r requirements.txt"
}

$lanIp = '127.0.0.1'

$ipConfig = ipconfig.exe 2>$null
foreach ($line in $ipConfig) {
    if ($line -match 'IPv4 Address.*:\s*(\d+\.\d+\.\d+\.\d+)') {
        $candidate = $matches[1]
        if ($candidate -notmatch '^127\.' -and $candidate -notmatch '^169\.254\.') {
            $lanIp = $candidate
            break
        }
    }
}

$envContents = @(
    '# Auto-generated by start-dev.ps1',
    "EXPO_PUBLIC_API_URL=http://$lanIp:8000",
    ''
) -join [Environment]::NewLine

Set-Content -Path $frontendEnv -Value $envContents -Encoding UTF8
Write-Host "Expo backend URL set to: http://$lanIp:8000"

Write-Host 'Starting FastAPI backend on 0.0.0.0:8000...'
$backend = Start-Process -FilePath $venvPython -ArgumentList @('-m', 'uvicorn', 'main:app', '--host', '0.0.0.0', '--port', '8000') -WorkingDirectory $repoRoot -PassThru

for ($i = 0; $i -lt 30; $i++) {
    try {
        $health = Invoke-WebRequest -Uri 'http://localhost:8000/api/health' -TimeoutSec 2 -UseBasicParsing
        if ($health.StatusCode -ge 200 -and $health.StatusCode -lt 500) {
            break
        }
    }
    catch {
        Start-Sleep -Seconds 1
    }
}

if ($backend.HasExited) {
    throw 'FastAPI exited unexpectedly. Check the backend output and fix the startup error.'
}

Write-Host 'FastAPI is ready. Starting Expo web app...'
Set-Location $frontendDir
& npm run web
