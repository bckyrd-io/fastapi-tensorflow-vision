-- PostgreSQL schema for AquaMonitor. Create db_pond first, then run this file.

CREATE TABLE ponds (
  id VARCHAR(10) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  location VARCHAR(200),
  size_sqm NUMERIC(8,2),
  depth_m NUMERIC(4,2),
  species VARCHAR(50),
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pond_configs (
  pond_id VARCHAR(10) PRIMARY KEY REFERENCES ponds(id) ON DELETE CASCADE,
  temp_min NUMERIC(4,2) DEFAULT 24.00,
  temp_optimal NUMERIC(4,2) DEFAULT 26.00,
  temp_max NUMERIC(4,2) DEFAULT 28.00,
  ph_min NUMERIC(4,2) DEFAULT 6.50,
  ph_optimal NUMERIC(4,2) DEFAULT 7.00,
  ph_max NUMERIC(4,2) DEFAULT 8.00,
  humidity_min INTEGER DEFAULT 60,
  humidity_optimal INTEGER DEFAULT 75,
  humidity_max INTEGER DEFAULT 85,
  water_level_min NUMERIC(4,2) DEFAULT 0.80,
  water_level_optimal NUMERIC(4,2) DEFAULT 1.50,
  water_level_max NUMERIC(4,2) DEFAULT 1.80,
  device_id VARCHAR(50),
  device_name VARCHAR(100),
  device_mac VARCHAR(17)
);

CREATE TABLE sensors (
  id VARCHAR(20) PRIMARY KEY,
  pond_id VARCHAR(10) REFERENCES ponds(id) ON DELETE CASCADE,
  type VARCHAR(20) CHECK (type IN ('temperature', 'ph', 'humidity', 'water_level')),
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sensor_readings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pond_id VARCHAR(10) REFERENCES ponds(id) ON DELETE CASCADE,
  temperature NUMERIC(4,2),
  ph NUMERIC(4,2),
  humidity INTEGER,
  water_level NUMERIC(4,2),
  device_id VARCHAR(50),
  reading_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE alerts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pond_id VARCHAR(10) REFERENCES ponds(id) ON DELETE CASCADE,
  type VARCHAR(10) NOT NULL DEFAULT 'info' CHECK (type IN ('critical', 'warning', 'info')),
  message TEXT NOT NULL,
  source VARCHAR(10) NOT NULL DEFAULT 'system' CHECK (source IN ('feeding', 'sensor', 'config', 'user', 'system')),
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  value NUMERIC(4,2),
  parameter VARCHAR(20) CHECK (parameter IN ('temperature', 'ph', 'humidity', 'water_level')),
  acknowledged_by VARCHAR(50),
  acknowledged_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE feeding_schedules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pond_id VARCHAR(10) NOT NULL REFERENCES ponds(id) ON DELETE CASCADE,
  time TIME,
  interval_minutes INTEGER,
  amount_grams INTEGER DEFAULT 0,
  days VARCHAR(50) DEFAULT 'Daily',
  feed_type VARCHAR(50) DEFAULT 'pellets',
  active BOOLEAN NOT NULL DEFAULT FALSE,
  last_executed TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE feeding_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pond_id VARCHAR(10) NOT NULL REFERENCES ponds(id) ON DELETE CASCADE,
  schedule_id INTEGER REFERENCES feeding_schedules(id) ON DELETE SET NULL,
  amount_grams INTEGER NOT NULL,
  triggered_by VARCHAR(10) NOT NULL DEFAULT 'schedule' CHECK (triggered_by IN ('schedule', 'manual')),
  triggered_by_user VARCHAR(50),
  device_id VARCHAR(50),
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'completed', 'failed')),
  fed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE feeding_schedule_states (
  preset_id VARCHAR(20) PRIMARY KEY,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(100),
  role VARCHAR(10) NOT NULL DEFAULT 'operator' CHECK (role IN ('admin', 'operator', 'viewer')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_login TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_alerts_status_type ON alerts (status, type);
CREATE INDEX idx_alerts_source ON alerts (source);
CREATE INDEX idx_alerts_created ON alerts (created_at);
CREATE INDEX idx_alerts_pond ON alerts (pond_id);
CREATE INDEX idx_feeding_logs_pond_created ON feeding_logs (pond_id, created_at);
CREATE INDEX idx_feeding_logs_schedule ON feeding_logs (schedule_id);
CREATE INDEX idx_feeding_schedules_pond_active ON feeding_schedules (pond_id, active);
CREATE INDEX idx_sensors_pond ON sensors (pond_id);
CREATE INDEX idx_sensor_readings_pond_time ON sensor_readings (pond_id, reading_time);

-- Keep automatic updated_at timestamps on these tables.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ponds_set_updated_at
  BEFORE UPDATE ON ponds FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER feeding_schedules_set_updated_at
  BEFORE UPDATE ON feeding_schedules FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER feeding_schedule_states_set_updated_at
  BEFORE UPDATE ON feeding_schedule_states FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER users_set_updated_at
  BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
